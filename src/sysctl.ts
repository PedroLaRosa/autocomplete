const generateSysctlNames: Fig.Generator = {
  script: ["sysctl", "-A", "-N"],
  postProcess: (out) => {
    return out
      .split("\n")
      .filter((line) => line.trim() !== "")
      .map((line) => {
        return {
          name: line,
          description: "Variable name",
        };
      });
  },
};

