// Regenerates SUPPORTED_CLIS.md from the compiled specs in build/ and git history.
// Run via `pnpm cli-list` (builds first).
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import semver from "semver";

const root = new URL("..", import.meta.url);
const build = new URL("build/", root);
const { default: completions, diffVersionedCompletions } = await import(
  new URL("index.js", build)
);

// A CLI is a top-level spec ("git", "@scope/pkg"); "aws/s3"-style entries are subcommand files.
const clis = completions.filter(
  (n) => n.split("/").length === (n.startsWith("@") ? 2 : 1)
);

const describe = async (file) =>
  (await import(new URL(file, build))).default?.description?.trim();

async function description(name) {
  if (!diffVersionedCompletions.includes(name)) return describe(`${name}.js`);
  // Versioned spec: tabsmith loads the newest version file; older ones fill a missing description.
  const versions = readdirSync(new URL(`src/${name}/`, root))
    .filter((f) => f.endsWith(".ts") && semver.valid(f.slice(0, -3)))
    .map((f) => f.slice(0, -3))
    .sort(semver.rcompare);
  for (const v of versions) {
    const d = await describe(`${name}/${v}.js`);
    if (d) return d;
  }
}

const git = (...args) =>
  execFileSync("git", args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
if (git("rev-parse", "--is-shallow-repository").trim() === "true")
  throw new Error(
    "Shallow clone: dates need full history (git fetch --unshallow)"
  );

// Bulk no-op commits listed in .git-blame-ignore-revs don't count as updates.
const ignored = new Set(
  readFileSync(new URL(".git-blame-ignore-revs", root), "utf8")
    .split("\n")
    .map((l) => l.replace(/#.*/, "").trim().toLowerCase())
    .filter(Boolean)
    .map((sha) => {
      if (/^[0-9a-f]{40}$/.test(sha)) return sha;
      throw new Error(`.git-blame-ignore-revs: "${sha}" is not a full SHA`);
    })
);

// Newest commit date per CLI: src/<name>.ts plus anything under src/<name>/ (subcommands, versions).
// --cc lists files a merge changed against every parent (conflict resolutions).
// ponytail: renames aren't followed, so a pure move (e.g. dev/ -> src/ on 2021-09-17) counts as an update.
const updated = {};
let date;
const log = git(
  "-c",
  "core.quotePath=false",
  "log",
  "--cc",
  "--format=%x00%H %cs",
  "--name-only",
  "--relative",
  "--",
  "src"
);
for (const line of log.split("\n")) {
  if (line.startsWith("\0")) {
    const [sha, day] = line.slice(1).split(" ");
    date = ignored.has(sha) ? null : day;
  } else if (line && date) {
    const parts = line.slice("src/".length).replace(/\.ts$/, "").split("/");
    const cli = parts.slice(0, parts[0].startsWith("@") ? 2 : 1).join("/");
    if (!(updated[cli] >= date)) updated[cli] = date;
  }
}

const cell = (s) =>
  s ? s.replace(/\s+/g, " ").replace(/\|/g, "\\|").replace(/</g, "&lt;") : "—";
const descriptions = await Promise.all(clis.map(description));
const rows = clis.map(
  (n, i) => `| \`${n}\` | ${cell(descriptions[i])} | ${updated[n] ?? "—"} |`
);

writeFileSync(
  new URL("SUPPORTED_CLIS.md", root),
  [
    "# Supported CLIs",
    "",
    `The ${clis.length} CLIs tabsmith can autocomplete. "Last updated" is the date of the newest commit touching the spec, ignoring the bulk commits in \`.git-blame-ignore-revs\`.`,
    "",
    "<!-- Generated by `pnpm cli-list` (scripts/generate-cli-list.js). Do not edit by hand. -->",
    "",
    "| CLI | Description | Last updated |",
    "| --- | --- | --- |",
    ...rows,
    "",
  ].join("\n")
);

const undescribed = clis.filter((_, i) => !descriptions[i]);
console.log(
  `SUPPORTED_CLIS.md: ${clis.length} CLIs, ${undescribed.length} without a description`
);
const undated = clis.filter((n) => !updated[n]);
if (undated.length) console.warn(`No commit yet for: ${undated.join(", ")}`);
if (git("status", "--porcelain", "--", "src"))
  console.warn(
    "Uncommitted changes in src/ keep their old date: regenerate after committing."
  );
